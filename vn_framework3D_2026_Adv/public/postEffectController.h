#pragma once

//============================================================
// PostEffectValue
// ポストエフェクトの見た目をまとめた値
// これを Base値 / 演出ピーク値 として使う
//============================================================
struct PostEffectValue
{
	//============================================================
	// ColorGrading
	//============================================================
	float brightness = 1.04f;
	float contrast = 1.18f;
	float saturation = 1.15f;

	//============================================================
	// Vignette
	//============================================================
	float vignetteStart = 0.38f;
	float vignetteEnd = 0.80f;
	float vignetteStrength = 0.35f;

	//============================================================
	// Chromatic Aberration
	//============================================================
	float chromaticStrength = 0.002f;
};

//============================================================
// PostEffectController
// 被弾・パリィ・ダッシュなど
// ゲームイベントに応じたポストプロセス演出を管理するクラス
//============================================================
class PostEffectController
{
public:
	void Initialize();

	//============================================================
	// 毎フレーム更新
	// dt : 経過時間
	//============================================================
	void Update(float dt);

	//============================================================
	// 演出再生
	//============================================================
	void PlayDamageEffect();
	void PlayParryEffect();
	void PlayDashEffect();

	//============================================================
	// 通常状態の値を変更したい場合用
	//============================================================
	void SetBaseValue(const PostEffectValue& value);

private:
	//============================================================
	// 指定した値をPostProcessManagerへ反映する
	//============================================================
	void ApplyValue(const PostEffectValue& value);

	//============================================================
	// 一時演出を開始する
	// peakValue : 演出開始直後の強い値
	// duration  : 通常値へ戻るまでの時間
	//============================================================
	void StartImpulse(
		const PostEffectValue& peakValue,
		float duration
	);

	//============================================================
	// 補間用
	//============================================================
	static float Clamp01(float value);
	static float Lerp(float a, float b, float t);
	static PostEffectValue LerpValue(
		const PostEffectValue& a,
		const PostEffectValue& b,
		float t
	);

private:
	//============================================================
	// 通常時の値
	//============================================================
	PostEffectValue mBaseValue;

	//============================================================
	// 演出開始直後の強い値
	//============================================================
	PostEffectValue mPeakValue;

	//============================================================
	// 現在の値
	//============================================================
	PostEffectValue mCurrentValue;

	//============================================================
	// 演出タイマー
	//============================================================
	float mTimer = 0.0f;
	float mDuration = 0.0f;
};
