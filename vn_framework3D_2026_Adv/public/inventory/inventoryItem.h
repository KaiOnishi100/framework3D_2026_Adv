#pragma once

#include <string>
#include <cstdint>


//============================================================
// Inventory Item Type
//============================================================
enum class InventoryItemType : std::uint32_t
{
    //========================================================
    // 鍵など
    //========================================================
    KeyItem = 0,

    //========================================================
    // Puzzleへ使用するアイテム
    //========================================================
    PuzzleItem,

    //========================================================
    // 回復など
    //========================================================
    Consumable,

    //========================================================
    // 文書 / メモ
    //========================================================
    Document
};


//============================================================
// Inventory Item Definition
// アイテムそのものの情報
//============================================================
struct InventoryItemDefinition
{
    //========================================================
    // 固有ID
    //========================================================
    std::string Id;

    //========================================================
    // UI表示名
    //========================================================
    std::wstring Name;

    //========================================================
    // 説明
    //========================================================
    std::wstring Description;

    //========================================================
    // 種類
    //========================================================
    InventoryItemType Type = InventoryItemType::KeyItem;

    //========================================================
    // 最大所持数
    // Key Itemなら基本1
    //========================================================
    std::uint32_t MaxCount =1;
};


//============================================================
// Inventory Entry
// Playerが実際に持っている状態
//============================================================
struct InventoryEntry
{
    std::string ItemId;

    std::uint32_t Count = 0;
};