#pragma once


class ObjectBase;
class PlayerMovement;
class NoiseSystem;


//============================================================
// Player Noise Emitter
// Playerの:
// ・Walk
// ・Sprint
// から足音Noise Eventを生成する
//============================================================
class PlayerNoiseEmitter
{
public:

    //========================================================
    // Noise System接続
    //========================================================
    void SetNoiseSystem(NoiseSystem* system )
    {
        mNoiseSystem = system;
    }


    //========================================================
    // Update
    //========================================================
    void Update(float dt, const ObjectBase& owner, const PlayerMovement& movement);


private:

    //========================================================
    // Noise System
    //========================================================
    NoiseSystem* mNoiseSystem = nullptr;

    //========================================================
    // 歩き・走りそれぞれの足音素材を1歩ごとに順番に切り替える
    //========================================================
    int mFootstepVariant = 0;

    //========================================================
    // プレイヤーに聞こえる足音SEの間隔を管理する
    //========================================================
    float mFootstepSfxTimer = 0.0f;

    //========================================================
    // Footstep Timer
    //========================================================
    float mFootstepTimer = 0.0f;

    //========================================================
    // Walk
    //========================================================
    float mWalkRadius = 4.0f;
    float mWalkInterval = 0.55f;

    //========================================================
    // Sprint
    //========================================================
    float mSprintRadius = 9.0f;
    float mSprintInterval = 0.30f;

    //============================================================
    // Crouch Footstep
    //============================================================
    float mCrouchRadius = 1.5f;

    //============================================================
    // しゃがみ歩行の足音間隔
    //============================================================
    float mCrouchInterval = 0.80f;

    //============================================================
    // Noise強度
    //============================================================
    float mCrouchIntensity = 0.35f;
};