#include "../../../../framework.h"
#include "../../../../framework/vn_environment.h"

#include "../player/explorationPlayer.h"

#include "debugInteractObject.h"


//============================================================
// Constructor
//============================================================
DebugInteractObject::DebugInteractObject(const WCHAR* folder, const WCHAR* modelFile) : ModelBase(folder, modelFile)
{
    //========================================================
    // Debug ObjectなのでLightingを使用
    //========================================================
    SetPBREnabled(true);

    //========================================================
    // 初期状態
    //========================================================
    setDiffuse(0.35f, 0.35f, 0.35f, 1.0f);

    SetMetallic(0.0f);

    SetRoughness(0.6f);
}


//============================================================
// Position
//============================================================
void DebugInteractObject::SetDebugPosition(
    float x,
    float y,
    float z
)
{
    //========================================================
    // Render Object位置
    //========================================================
    setPosition(x, y, z);

    //========================================================
    // Interaction判定位置
    //========================================================
    mInteractionPosition = XMVectorSet(x, y, z, 1.0f);
}


//============================================================
// Interact
//============================================================
void DebugInteractObject::Interact(ExplorationPlayer& player)
{
    //========================================================
    // 今回Player情報は使用しない
    //========================================================
    (void)player;

    //========================================================
    // State Toggle
    //========================================================
    mActivated = !mActivated;


    //========================================================
    // 視覚的にもInteraction成功を確認できるようにする
    //========================================================
    if (mActivated)
    {
        //====================================================
        // ON
        //====================================================
        setDiffuse(0.15f, 1.0f, 0.20f, 1.0f);

        OutputDebugStringW(L"[DebugInteractObject] " L"Interacted : ON\n");
    }
    else
    {
        //====================================================
        // OFF
        //====================================================
        setDiffuse(0.35f, 0.35f, 0.35f, 1.0f);

        OutputDebugStringW(L"[DebugInteractObject] " L"Interacted : OFF\n");
    }
}