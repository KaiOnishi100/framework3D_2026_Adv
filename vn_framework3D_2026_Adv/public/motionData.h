#pragma once

//============================================================
// MOT V2 Runtime Data
// .motファイルを読み込んだ後Runtime上では
// この構造体として保持する
//============================================================
struct MotionDataV2
{
    //========================================================
    // MOT Header
    //========================================================
    vnMotionDataV2 Header = {};

    //========================================================
    // Bone Track
    // 1 Track = 1 Skeleton Node
    //========================================================
    std::vector<vnMotionData_TrackV2> Tracks;

    //========================================================
    // Position / Scale Key
    //========================================================
    std::vector<vnMotionData_VectorKeyV2> VectorKeys;

    //========================================================
    // Rotation Quaternion Key
    //========================================================
    std::vector<vnMotionData_QuaternionKeyV2> QuaternionKeys;
};