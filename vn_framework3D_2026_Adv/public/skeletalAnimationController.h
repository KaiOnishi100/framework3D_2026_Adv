#pragma once

class SkeletalModel;

//============================================================
// SkeletalAnimationController
// ゲーム側の状態から、
// SkeletalModelで再生するAnimationを選択する
// SkeletalModel: Animationを「再生する装置」
// Controller: どのAnimationを再生するか「判断する装置」
// と役割を分離する
//============================================================
class SkeletalAnimationController
{
public:

    //========================================================
    // Locomotion State
    //========================================================
    enum class State
    {
        None,

        Idle,

        Walk,

        Run,

        Attack
    };

    //============================================================
    // Combo Step
    // 1段分のAttack Animation設定
    // InputStartNormalized / InputEndNormalized:
    //      次のAttack入力を受け付ける時間。
    //      0.0 ～ 1.0 のAnimation進行率で指定する
    // TransitionNormalized:
    //      次Attackが予約されている場合に、
    //      実際に次Animationへ切り替える時間
    //============================================================
    struct ComboStep
    {
        //========================================================
        // 使用するAnimation
        //========================================================
        std::wstring MotionName;

        //========================================================
        // このAttackへ入るBlend時間
        //========================================================
        float BlendInDuration = 0.08f;

        //========================================================
        // 次Attack入力受付開始
        // 0.35 = Animationの35%
        //========================================================
        float InputStartNormalized = 0.35f;

        //========================================================
        // 次Attack入力受付終了
        // 0.85 = Animationの85%
        //========================================================
        float InputEndNormalized = 0.85f;


        //========================================================
        // 次Attackへの遷移地点
        // 入力予約済みなら
        // Animationの70%地点から次へBlendする
        //========================================================
        float TransitionNormalized = 0.70f;
    };

private:

    //========================================================
    // 操作対象のSkeletalModel
    //========================================================
    SkeletalModel* mModel = nullptr;


    //========================================================
    // 現在State
    //========================================================
    State mCurrentState = State::None;

    //============================================================
    // 現在のLocomotion State
    //============================================================
    State mLocomotionState = State::Idle;

    //============================================================
    // Combo Definition
    //============================================================
    std::vector<ComboStep> mComboSteps;

    //============================================================
    // 現在再生しているOne Shot名
    //============================================================
    std::wstring mOneShotMotionName;


    //============================================================
    // 現在何段目か
    //============================================================
    int mComboIndex = -1;

    //============================================================
    // One Shot終了後のBlend時間
    //============================================================
    float mOneShotBlendOutDuration = 0.15f;

    //============================================================
    // Combo終了後Locomotionへ戻るBlend時間
    //============================================================
    float mComboReturnBlendDuration = 0.15f;

    //============================================================
    // One Shot Animation中か
    //============================================================
    bool mOneShotActive = false;

    //============================================================
    // 現在Combo中か
    //============================================================
    bool mComboActive = false;

    //============================================================
    // 次Attack入力が予約されているか
    //============================================================
    bool mComboNextQueued = false;


public:

    //========================================================
    // Constructor
    //========================================================
    explicit SkeletalAnimationController(SkeletalModel* model);


    //========================================================
    // 初期化
    // Idle / Walk / Runがロード済みか確認し
    // Idleから開始する
    //========================================================
    bool Initialize();


    //========================================================
    // Animation State更新
    //========================================================
    void Update(bool isMoving, bool isRunning);


    //========================================================
    // 現在State
    //========================================================
    State GetCurrentState() const
    {
        return mCurrentState;
    }

    bool PlayAttack(
        const std::wstring& motionName,
        float blendIn = 0.10f,
        float blendOut = 0.15f
    );

public:
    //============================================================
    // Combo登録API関数
    //============================================================

    //============================================================
    // Combo定義を全削除
    //============================================================
    void ClearComboDefinition();


    //============================================================
    // Combo Step追加
    //============================================================
    bool AddComboStep(
        const std::wstring& motionName,
        float blendInDuration = 0.08f,
        float inputStartNormalized = 0.35f,
        float inputEndNormalized = 0.85f,
        float transitionNormalized = 0.70f
    );


    //============================================================
    // Attack入力
    // Comboしていなければ1段目開始
    // Combo中なら、入力受付時間内であれば
    // 次Attackを予約する
    //============================================================
    bool RequestComboAttack();


    //============================================================
    // Combo中か
    //============================================================
    bool IsComboActive() const
    {
        return mComboActive;
    }


    //============================================================
    // 現在Combo段数
    //
    // 0 = Comboなし
    // 1 = 1段目
    // 2 = 2段目...
    //============================================================
    int GetComboCount() const
    {
        if (!mComboActive)
        {
            return 0;
        }

        return
            mComboIndex + 1;
    }

private:

    //============================================================
    // 入力状態からLocomotion Stateを決定
    //============================================================
    State DetermineLocomotionState(
        bool isMoving,
        bool isRunning
    ) const;


    //============================================================
    // State → Motion Name
    //============================================================
    const wchar_t* GetLocomotionMotionName(State state) const;

    //========================================================
    // State変更
    //========================================================
    void ChangeState(State nextState);

private:
    //============================================================
    // Combo更新
    //============================================================
    void UpdateCombo();


    //============================================================
    // 指定Combo Step開始
    //============================================================
    bool StartComboStep(int comboIndex );


    //============================================================
    // Combo終了
    //============================================================
    void FinishCombo();


    //============================================================
    // Locomotionへ戻る
    //============================================================
    void ReturnToLocomotion( float blendDuration );
};