#pragma once

//------------------------------------------------------------
// UI用の矩形（左上基準）
//  x,y : 左上
//  w,h : 幅・高さ
//------------------------------------------------------------
struct UIRect
{
	float x = 0;;
	float y = 0;
	float w = 0;
	float h = 0;
};
static void UI_GetMouseVirtual(float& outX, float& outY);
//------------------------------------------------------------
// マウスがUIRectの上にあるか
//------------------------------------------------------------
bool UI_IsHover(const UIRect& r);
//------------------------------------------------------------
// 左クリックした瞬間（トリガー）かつ hover のとき
//------------------------------------------------------------
bool UI_IsClicked(const UIRect& r);
