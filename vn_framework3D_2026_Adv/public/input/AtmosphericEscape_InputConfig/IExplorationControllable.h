#pragma once

//============================================================
// IExplorationControllable
// Atmospheric Escape Game用の操作Interface
//============================================================
class IExplorationControllable
{
public:

    virtual ~IExplorationControllable() = default;


    //========================================================
    // 操作ロック
    //========================================================
    virtual bool IsControlLocked() const
    {
        return false;
    }

    //========================================================
    // 移動入力
    // x:
    //   -1.0 = 左
    //   +1.0 = 右
    // y:
    //   -1.0 = 後ろ
    //   +1.0 = 前
    //========================================================
    virtual void AddMoveAxis(  float x,  float y ) = 0;

    //========================================================
    // Sprint
    //========================================================
    virtual void SetSprint( bool sprint  ) = 0;

    //========================================================
    // Interaction
    //========================================================
    virtual void Interact() = 0;

    //========================================================
    // 視点変更
    //========================================================
    virtual void ToggleViewMode() = 0;

    //========================================================
    // Flashlight
    //========================================================
    virtual void ToggleFlashlight() = 0;

    //============================================================
    // Crouch
    //============================================================
    virtual void SetCrouching(bool crouching) = 0;

    //============================================================
    // Crouch状態取得
    //============================================================
    virtual bool IsCrouching() const = 0;
};