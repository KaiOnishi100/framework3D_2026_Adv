//============================================================
// Persistent Object Type
//
// SaveDataをDebugしたときに、
// 何のObjectなのか分かるように保持する
//============================================================
enum class PersistentObjectType : std::uint32_t
{
    Unknown = 0,
    Door,
    Puzzle,
    Pickup,
    Switch,
    Terminal
};


//============================================================
// World Object Save State
// CSV上の固有IDをKeyとしてRuntime Objectを復元する
//============================================================
struct WorldObjectSaveState
{
    //========================================================
    // CSV / World上の固有ID
    // "MainHall_WestDoor"
    // "Library_ClockPuzzle"
    // "FacilityAccessKey"
    //========================================================
    std::string Id;

    //========================================================
    // Object Type
    //========================================================
    PersistentObjectType Type = PersistentObjectType::Unknown;

    //========================================================
    // Main State
    //========================================================
    std::uint32_t State = 0;

    //========================================================
    // Flags
    // bit flag用。
    // bit0 = Locked
    // bit1 = Enabled
    // bit2 = Used
    //========================================================
    std::uint32_t Flags = 0;

    //========================================================
    // 汎用Value
    //========================================================
    float Value = 0.0f;
};

//============================================================
// AtmosphericEscape Save Data
//============================================================
struct AtmosphericEscapeSaveData
{
    //========================================================
    // File Header
    //========================================================

    // ファイルがAtmosphericEscapeのSaveか確認するための値
    std::uint32_t Magic = 0x41544553; // "ATES"

    // SaveData構造を変更したときに増やす
    std::uint32_t Version = 3;

    //========================================================
    // Player
    //========================================================
    XMFLOAT3 PlayerPosition =
    {
        0.0f,
        0.0f,
        0.0f
    };

    float PlayerHealth = 100.0f;


    //========================================================
    // Game Progress
    //========================================================
    std::uint32_t ExplorationPhase = 0;

    //========================================================
    // Play Time
    //========================================================
    float PlayTime = 0.0f;

    //========================================================
    // Current Objective
    //========================================================
    std::string CurrentObjectiveId;

    //========================================================
    // Inventory
    //========================================================
    std::vector<InventoryEntry> Inventory;

    //========================================================
    // Map Discovery
    // 一度訪れたRoom ID
    //========================================================
    std::vector<std::string> DiscoveredRooms;

    std::vector<WorldObjectSaveState> WorldObjects;
};