#pragma once

class vnScene;

//============================================================
// FacilityPowerLight
// 施設電源に連動する照明
// OFF:
//   ・Point Lightなし
//   ・Emissiveも暗い
//
// ON:
//   ・Point Lightを毎Frame登録
//   ・Lamp Modelを発光させる
//============================================================
class FacilityPowerLight
{
public:

    FacilityPowerLight() = default;

    ~FacilityPowerLight() = default;


    //========================================================
    // Initialize
    //========================================================
    bool Initialize(
        vnScene* scene,
        const XMFLOAT3& position,
        const XMFLOAT3& scale
    );


    //========================================================
    // Terminate
    //========================================================
    void Terminate(vnScene* scene);


    //========================================================
    // Update
    //========================================================
    void Update();


    //========================================================
    // Power
    //========================================================
    void SetPowered(bool powered);


    bool IsPowered() const
    {
        return mPowered;
    }


private:

    //========================================================
    // Lamp Model
    //========================================================
    ModelBase* mModel = nullptr;

    //========================================================
    // Light Position
    //========================================================
    XMFLOAT3 mPosition =
    {
        0.0f,
        0.0f,
        0.0f
    };


    //========================================================
    // Light Parameters
    //========================================================
    XMFLOAT3 mColor =
    {
        1.0f,
        0.82f,
        0.62f
    };


    float mRange = 5.5f;

    float mIntensity = 8.0f;

    //========================================================
    // Power State
    //========================================================
    bool mPowered = false;
};