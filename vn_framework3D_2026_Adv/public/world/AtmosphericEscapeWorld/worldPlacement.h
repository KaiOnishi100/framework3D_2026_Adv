#pragma once

//============================================================
// WorldObjectPlacement
// CSVに書かれている1Object分の配置情報
//      Position
//      Rotation
//      Scale
// を外部ファイルから取得することだけを担当する
//============================================================
struct WorldObjectPlacement
{
    //========================================================
    // Object固有ID
    // Example:
    // Ground
    // FacilityMain
    // EntranceDoor
    // Tree001
    //========================================================
    std::string Id;


    //========================================================
    // Object種類
    // 同じ種類のObjectをまとめて取得するときに使用する
    // Example:
    // Ground
    // Facility
    // FacilityDoor
    // Tree
    //========================================================
    std::string Prefab;


    //========================================================
    // Transform
    //========================================================
    XMFLOAT3 Position =
    {
        0.0f,
        0.0f,
        0.0f
    };


    XMFLOAT3 Rotation =
    {
        0.0f,
        0.0f,
        0.0f
    };


    XMFLOAT3 Scale =
    {
        1.0f,
        1.0f,
        1.0f
    };

    //============================================================
    // Optional Data ID
    // Prefab固有の追加データ
    //============================================================
    std::string DataId;
};


//============================================================
// WorldPlacementTable
// CSVを読み込み
// WorldObjectPlacementとして保持する
//============================================================
class WorldPlacementTable
{
public:

    //========================================================
    // CSV Load
    //========================================================
    bool Load(const std::filesystem::path& filePath);

    //========================================================
    // CSV追加読み込み
    // 既存Placementを残したまま新しいCSVを追加する
    //========================================================
    bool Append(const std::filesystem::path& filePath);

    //========================================================
    // 複数CSV一括読み込み
    // 最初に1度だけClearし指定されたCSVを順番にMergeする
    //========================================================
    bool LoadFiles(const std::vector<std::filesystem::path>& filePaths);

    //========================================================
    // 全データ削除
    //========================================================
    void Clear();


    //========================================================
    // IDから検索
    // 見つからなければnullptr
    //========================================================
    const WorldObjectPlacement* Find(const std::string& id) const;


    //========================================================
    // Prefabから複数検索
    // Treeなど同種類のObjectをまとめて生成するときに使用
    //========================================================
    std::vector<const WorldObjectPlacement*> FindByPrefab(const std::string& prefab) const;


private:

    //========================================================
    // CSV Utility
    //========================================================
    static std::string Trim(const std::string& text);

    static std::vector<std::string> SplitLine(const std::string& line);


private:

    //========================================================
    // 実データ
    //========================================================
    std::vector<WorldObjectPlacement> mPlacements;


    //========================================================
    // ID検索高速化
    // Id
    //   ↓
    // mPlacementsのIndex
    //========================================================
    std::unordered_map<std::string, size_t> mIdLookup;
};