#pragma once

#include"../../../../framework/vn_environment.h"


//============================================================
// Exploration Area
// 大きな建物・エリア単位
//============================================================
enum class ExplorationArea
{
    Unknown = 0,

    //========================================================
    // 本館
    //========================================================
    MainBuilding,

    //========================================================
    // 中庭
    //========================================================
    Courtyard,

    //========================================================
    // 別館
    //========================================================
    Annex,

    //========================================================
    // 現在の開発用Facility
    //========================================================
    TestFacility
};


//============================================================
// Exploration Floor
//============================================================
enum class ExplorationFloor
{
    Unknown = 0,

    //========================================================
    // 地下1階
    //========================================================
    Basement1,

    //========================================================
    // 1階
    //========================================================
    Floor1,

    //========================================================
    // 2階
    //========================================================
    Floor2,

    //========================================================
    // 中庭など
    //========================================================
    Outdoor
};


//============================================================
// Room Definition
// World上の部屋を定義する
// 現段階ではAABB
//============================================================
struct RoomDefinition
{
    //========================================================
    // 固有ID
    // Save / Objective / Mapから共通して使用する
    //========================================================
    std::string Id;

    //========================================================
    // UI表示名
    //========================================================
    std::wstring DisplayName;

    //========================================================
    // Area
    //========================================================
    ExplorationArea Area = ExplorationArea::Unknown;

    //========================================================
    // Floor
    //========================================================
    ExplorationFloor Floor = ExplorationFloor::Unknown;

    //========================================================
    // World AABB
    // この範囲にPlayerが入った場合、
    // 現在地をこのRoomと判断する
    //========================================================
    XMFLOAT3 MinBounds =
    {
        0.0f,
        0.0f,
        0.0f
    };


    XMFLOAT3 MaxBounds =
    {
        0.0f,
        0.0f,
        0.0f
    };
};


//============================================================
// 現在地
//============================================================
struct ExplorationLocation
{
    ExplorationArea Area = ExplorationArea::Unknown;

    ExplorationFloor Floor = ExplorationFloor::Unknown;

    std::string RoomId;
};