#pragma once

#include"explorationLocationSystem.h"


//============================================================
// Objective Navigation Type
//============================================================
enum class ObjectiveNavigationType
{
    //========================================================
    // Navigationなし
    // Puzzleなど
    // Hintだけ与えてPlayerに探索させる
    //========================================================
    None = 0,


    //========================================================
    // Roomまでは教える
    // Itemそのものの正確な場所は教えない
    //========================================================
    Room,


    //========================================================
    // 正確なWorld Positionまで表示
    // Tutorial等だけで使う
    //========================================================
    WorldPosition
};


//============================================================
// Exploration Objective
//============================================================
struct ExplorationObjective
{
    //========================================================
    // Objective ID
    //========================================================
    std::string Id;


    //========================================================
    // HUD Text
    //========================================================
    std::wstring Text;


    //========================================================
    // 補助Hint
    // 必要ない場合は空文字
    //========================================================
    std::wstring Hint;


    //========================================================
    // Navigation
    //========================================================
    ObjectiveNavigationType Navigation = ObjectiveNavigationType::None;

    //========================================================
    // Room Navigation
    //========================================================
    ExplorationArea TargetArea = ExplorationArea::Unknown;
    ExplorationFloor TargetFloor = ExplorationFloor::Unknown;

    std::string TargetRoomId;


    //========================================================
    // Exact Position Navigation
    //========================================================
    XMFLOAT3 TargetPosition =
    {
        0.0f,
        0.0f,
        0.0f
    };
};