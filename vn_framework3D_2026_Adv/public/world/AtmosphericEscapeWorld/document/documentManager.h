#pragma once



//============================================================
// Document Definition
// ゲーム中に存在する文書そのものの定義
// 例:
//   DOC_001
//   「使用人への通達」
// Definition: 文書の固定データ
// DocumentManager: プレイヤーが何を取得したかというRuntime状態
// を分離して管理する
//============================================================
struct DocumentDefinition
{
    //========================================================
    // 一意ID
    // SaveData / World Placement / DocumentPickupから
    // このIDを使用して参照する
    //========================================================
    std::string Id;


    //========================================================
    // UI表示タイトル
    // 例: L"使用人への通達"
    //========================================================
    std::wstring Title;


    //========================================================
    // 文書の作成者
    // 空文字も許可する
    // 例:
    //   L"管理責任者"
    //   L"エリアス・ヴェイラン"
    //   L"マーラ"
    //========================================================
    std::wstring Author;


    //========================================================
    // 本文
    // Documents.csv + txtファイルから読み込む
    // RuntimeではUIがそのまま表示できるよう
    // Definition側に本文を保持しておく
    //========================================================
    std::wstring Body;


    //========================================================
    // ストーリー上の並び順
    // ※取得順とは別
    //========================================================
    std::uint32_t DisplayOrder = 0u;
};


//============================================================
// Document Manager
// Documentは
// ・消費しない
// ・個数を持たない
// ・一度取得したら永久に閲覧可能
//============================================================
class DocumentManager
{
public:

    //========================================================
    // Definition登録
    // 同じIDが既に存在する場合はfalse
    //========================================================
    bool RegisterDefinition(const DocumentDefinition& definition);

    //========================================================
    // Definition検索
    // 見つからなければnullptr
    //========================================================
    const DocumentDefinition* FindDefinition(const std::string& documentId) const;

    //========================================================
    // Document取得
    // true: 今回初めて取得した
    // false:
    //   ・存在しないDocument
    //   ・既に取得済み
    //========================================================
    bool CollectDocument(const std::string& documentId);


    //========================================================
    // 取得済み判定
    //========================================================
    bool IsCollected(const std::string& documentId) const;


    //========================================================
    // 取得済みDocument一覧
    // 取得した順番で返す
    // Document UIの一覧表示に使用する
    //========================================================
    std::vector<const DocumentDefinition*> GetCollectedDocuments() const;


    //========================================================
    // Save用
    // 取得済みDocument IDを
    // 取得順で返す
    //========================================================
    const std::vector<std::string>& GetCollectedDocumentIds() const
    {
        return mCollectedDocumentIds;
    }


    //========================================================
    // Load用
    // SaveDataに保存されていたDocument一覧を復元する
    // Runtimeに存在しないIDは無視する
    //========================================================
    void RestoreCollectedDocuments(const std::vector<std::string>& documentIds);


    //========================================================
    // Definition数
    //========================================================
    std::size_t GetDefinitionCount() const
    {
        return mDefinitions.size();
    }


    //========================================================
    // 取得済み数
    //========================================================
    std::size_t GetCollectedCount() const
    {
        return mCollectedDocumentIds.size();
    }


    //========================================================
    // 全状態Clear
    // Scene破棄時やContent再読み込み時に使用可能
    //========================================================
    void Clear();


private:

    //========================================================
    // Document Definition
    // Key: Document ID
    // Value: Document固定情報
    //========================================================
    std::unordered_map<std::string,DocumentDefinition> mDefinitions;


    //========================================================
    // 取得済みID
    // vector: 取得順を保持
    // unordered_set: 高速な重複判定
    //========================================================
    std::vector<std::string> mCollectedDocumentIds;

    std::unordered_set<std::string> mCollectedDocumentSet;
};
