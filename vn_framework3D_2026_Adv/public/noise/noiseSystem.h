#pragma once

#include "../../framework/vn_environment.h"

//============================================================
// Noise Type
// Gameplay上で発生するAIが聞く音の種類
//============================================================
enum class NoiseType
{
    FootstepWalk,
    FootstepSprint,

    Door,

    Terminal,

    Impact
};


//============================================================
// Noise Event
// どこで,どのくらいの範囲に音が発生したか。
//============================================================
struct NoiseEvent
{
    //========================================================
    // 音源位置
    //========================================================
    XMFLOAT3 Position =
    {
        0.0f,
        0.0f,
        0.0f
    };


    //========================================================
    // 聞こえる最大距離
    //========================================================
    float Radius = 0.0f;

    //========================================================
    // 音の種類
    //========================================================
    NoiseType Type = NoiseType::Impact;


    //========================================================
    // 優先度
    // 同Frameに複数のNoiseが発生した場合、
    // どの音を優先して調査するかに使用する
    // 通常 = 1.0
    // 大きい音 = 1.5～2.0
    //========================================================
    float Priority = 1.0f;
};


//============================================================
// Noise System
// Gameplay用の一時的なNoise Eventを管理する
//============================================================
class NoiseSystem
{
public:

    //========================================================
    // Frame Begin
    // Noise EventはそのFrameだけ有効
    //========================================================
    void BeginFrame()
    {
        mEvents.clear();
    }


    //========================================================
    // Noise発生
    //========================================================
    void Emit(const XMFLOAT3& position, float radius, NoiseType type, float priority = 1.0f)
    {
        //====================================================
        // 無効なNoiseは登録しない
        //====================================================
        if (radius <= 0.0f)
        {
            return;
        }


        NoiseEvent event;

        event.Position = position;
        event.Radius = radius;
        event.Type = type;
        event.Priority = priority;
        mEvents.push_back(event);
    }


    //========================================================
    // 現FrameのNoise一覧
    //========================================================
    const std::vector<NoiseEvent>& GetEvents() const
    {
        return mEvents;
    }


private:

    //========================================================
    // Current Frame Noise
    //========================================================
    std::vector<NoiseEvent> mEvents;
};