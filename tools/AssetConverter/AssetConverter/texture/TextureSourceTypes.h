#pragma once

//============================================================
// Standard Library
//============================================================
#include <string>


//============================================================
// Texture Source Type
//============================================================
enum class TextureSourceType
{
    //========================================================
    // Textureなし
    //========================================================
    None,

    //========================================================
    // File System上のTexture
    //========================================================
    ExternalFile,

    //========================================================
    // FBX / GLB内部に埋め込まれたTexture
    //========================================================
    Embedded
};


//============================================================
// 解決済みTexture参照
//============================================================
struct ResolvedTexture
{
    //========================================================
    // Textureの格納場所
    //========================================================
    TextureSourceType Type = TextureSourceType::None;

    //========================================================
    // ExternalFileの場合
    //========================================================
    std::string Path;

    //========================================================
    // Embeddedの場合
    //========================================================
    int EmbeddedIndex = -1;

    //========================================================
    // 有効なTexture参照か
    //========================================================
    bool IsValid() const
    {
        return Type != TextureSourceType::None;
    }
};


//============================================================
// Materialが参照している元Texture一式
//============================================================
struct ResolvedTextureSet
{
    //========================================================
    // BaseColor
    //========================================================
    ResolvedTexture BaseColor;

    //========================================================
    // Normal
    //========================================================
    ResolvedTexture Normal;

    //========================================================
    // Engine用ORMが元から存在する場合
    //========================================================
    ResolvedTexture ORM;

    //========================================================
    // ORM生成用の個別Texture
    //========================================================
    ResolvedTexture AO;

    ResolvedTexture Roughness;

    ResolvedTexture Metallic;

    //========================================================
    // SSS
    //========================================================
    ResolvedTexture Thickness;

    //========================================================
    // Emissive
    //========================================================
    ResolvedTexture Emissive;

    //========================================================
    // Skin Mask
    //========================================================
    ResolvedTexture SkinMask;

    //========================================================
    // Asset固有Material Mask
    // SkinMaskが直接存在しない場合の
    // 自動生成Sourceとして使用する
    //========================================================
    ResolvedTexture MaterialMask01;

    ResolvedTexture MaterialMask02;

};